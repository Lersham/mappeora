export type IconName = keyof typeof ICONS;

/** Sized by the font size around it (1em), so large text makes it larger too. */
export function Icon({ name, className = '' }: { name: IconName; className?: string }) {
  const Svg = ICONS[name];
  return <Svg className={`icon ${className}`} aria-hidden focusable={false} strokeWidth={2.25} />;
}
